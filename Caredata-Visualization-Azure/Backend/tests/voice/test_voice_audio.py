def test_vad_returns_empty_for_silence():
    audio, sr = _load("silence_5s.wav")
    assert voice_audio.vad_segments(audio, sr) == []


def test_vad_finds_voiced_segments_in_clean_voice():
    audio, sr = _load("clean_voice_10s.wav")
    segs = voice_audio.vad_segments(audio, sr)
    # Synthetic tone passes Silero's energy gate; we just need >= 1 segment
    assert len(segs) >= 1
    # Segments must be in [0, duration] and non-decreasing
    duration = audio.size / sr
    for s, e in segs:
        assert 0 <= s < e <= duration + 0.05


def test_vad_handles_empty_array():
    assert voice_audio.vad_segments(np.zeros(0, dtype=np.float32), 16000) == []



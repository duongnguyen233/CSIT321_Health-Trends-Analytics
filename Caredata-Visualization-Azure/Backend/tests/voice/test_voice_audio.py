def _full_offsets():
    return {
        "sustained_a": [0.0, 6.0],
        "ddk": [6.0, 11.0],
        "reading": [11.0, 18.0],
        "open_prompt": [18.0, 30.0],
    }


def test_split_stages_returns_four_arrays_with_correct_sizes():
    sr = 16000
    audio = np.zeros(int(30 * sr), dtype=np.float32)
    out = voice_audio.split_stages(audio, sr, _full_offsets())
    assert set(out.keys()) == set(_full_offsets().keys())
    assert out["sustained_a"].size == 6 * sr
    assert out["ddk"].size == 5 * sr
    assert out["reading"].size == 7 * sr
    assert out["open_prompt"].size == 12 * sr


def test_split_stages_missing_required_stage_raises():
    sr = 16000
    audio = np.zeros(int(30 * sr), dtype=np.float32)
    bad = {"sustained_a": [0.0, 6.0], "ddk": [6.0, 11.0]}  # missing 2 stages
    with pytest.raises(voice_audio.MissingStageError):
        voice_audio.split_stages(audio, sr, bad)


def test_split_stages_decreasing_range_raises():
    sr = 16000
    audio = np.zeros(int(30 * sr), dtype=np.float32)
    bad = dict(_full_offsets(), sustained_a=[5.0, 1.0])
    with pytest.raises(voice_audio.InvalidStageOffsetError):
        voice_audio.split_stages(audio, sr, bad)


def test_split_stages_out_of_bounds_clamps_end():
    """end past audio length is clamped (allows ~0.5s grace) but start
    well past duration raises."""
    sr = 16000
    audio = np.zeros(int(20 * sr), dtype=np.float32)
    # open_prompt extends past audio length; we accept the clamp.
    offsets = dict(_full_offsets(), open_prompt=[18.0, 30.0])
    out = voice_audio.split_stages(audio, sr, offsets)
    assert out["open_prompt"].size <= 12 * sr  # clamped
    # Start past the end raises explicitly
    bad = dict(_full_offsets(), reading=[100.0, 120.0])
    with pytest.raises(voice_audio.InvalidStageOffsetError):
        voice_audio.split_stages(audio, sr, bad)

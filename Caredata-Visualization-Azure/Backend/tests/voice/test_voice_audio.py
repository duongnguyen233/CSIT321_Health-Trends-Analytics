"""Tests for voice_audio: transcode, VAD, SNR, stage split.

Fixtures are committed under tests/voice/fixtures/ and are *synthetic* —
they are tones/noise generated by scripts/make_voice_fixtures.py, not real
human voice. Their job is to give each extractor a deterministic non-zero
input so the structural assertions hold.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from app.services import voice_audio


FIXTURES = Path(__file__).parent / "fixtures"


def _load(name: str):
    return voice_audio.load_wav((FIXTURES / name).read_bytes())


# ---------------------------------------------------------------------------
# load_wav
# ---------------------------------------------------------------------------


def test_load_wav_returns_float32_mono_at_16k():
    audio, sr = _load("clean_voice_10s.wav")
    assert sr == 16000
    assert audio.dtype == np.float32
    assert audio.ndim == 1


# ---------------------------------------------------------------------------
# transcode_to_wav
# ---------------------------------------------------------------------------


def test_transcode_passes_through_wav_input():
    """When input is already WAV, both ffmpeg and the soundfile fallback
    should produce a 16k mono PCM WAV."""
    raw = (FIXTURES / "clean_voice_10s.wav").read_bytes()
    out = voice_audio.transcode_to_wav(raw)
    audio, sr = voice_audio.load_wav(out)
    assert sr == 16000
    assert audio.ndim == 1
    # Duration should be ~10s (allow ~0.1s slack for ffmpeg framing)
    assert 9.5 <= audio.size / sr <= 10.5


@pytest.mark.skipif(
    not voice_audio.ffmpeg_available(),
    reason="ffmpeg not on PATH (winget install Gyan.FFmpeg)",
)
def test_transcode_handles_pure_silence_input():
    """ffmpeg path: even pure silence WAV transcodes successfully."""
    raw = (FIXTURES / "silence_5s.wav").read_bytes()
    out = voice_audio.transcode_to_wav(raw)
    audio, sr = voice_audio.load_wav(out)
    assert sr == 16000
    assert audio.size > 0


def test_transcode_decodes_browser_style_webm_opus_via_pyav():
    """Regression: browser uploads are WebM/Opus; libsndfile cannot decode
    those, and many machines have no system ffmpeg. The transcoder must
    fall back to PyAV's bundled libav so the worker pipeline still works.

    Without this, /api/voice/v2/upload accepts the file (202) but the
    background task crashes and the recording silently fails — the
    nurse dashboard never updates."""
    import io
    import av
    import numpy as np

    # Synthesise a 1.5 s 440 Hz tone, encode it as WebM/Opus exactly the
    # way Chrome's MediaRecorder would.
    sr = 48000
    t = np.arange(int(1.5 * sr)) / sr
    audio = (0.3 * np.sin(2 * np.pi * 440 * t)).astype(np.float32)
    buf = io.BytesIO()
    out = av.open(buf, mode="w", format="webm")
    stream = out.add_stream("libopus", rate=sr)
    stream.layout = "mono"
    frame = av.AudioFrame.from_ndarray(audio[None, :], format="flt", layout="mono")
    frame.rate = sr
    for packet in stream.encode(frame):
        out.mux(packet)
    for packet in stream.encode(None):
        out.mux(packet)
    out.close()
    webm_bytes = buf.getvalue()
    assert len(webm_bytes) > 0

    wav_bytes = voice_audio.transcode_to_wav(webm_bytes)
    decoded, decoded_sr = voice_audio.load_wav(wav_bytes)
    assert decoded_sr == 16000
    assert decoded.dtype == np.float32
    # Duration ~1.5s, allow ~50ms slack for codec framing
    assert 1.4 <= decoded.size / decoded_sr <= 1.6



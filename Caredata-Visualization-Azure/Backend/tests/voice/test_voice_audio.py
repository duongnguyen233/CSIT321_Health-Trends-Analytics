def test_snr_high_for_clean_voice_with_explicit_voiced_segments():
    """SNR math test: when we hand it the voiced regions ourselves the
    20*log10(rms_voiced/rms_silence) calculation should be well above 6 dB.

    (Silero VAD is trained on real speech and doesn't reliably segment our
    synthetic harmonic tones, so we bypass it here to test the math.)"""
    audio, sr = _load("clean_voice_10s.wav")
    # The fixture inserts silence pauses at [2.0, 2.5] and [6.0, 6.5];
    # voiced regions are everything else.
    voiced = [(0.0, 2.0), (2.5, 6.0), (6.5, 10.0)]
    snr = voice_audio.compute_snr_db(audio, sr, voiced=voiced)
    assert snr > 10.0, f"expected SNR >> 6 dB for clean voice fixture, got {snr}"


def test_snr_low_for_pure_noise():
    audio, sr = _load("noisy_5s.wav")
    snr = voice_audio.compute_snr_db(audio, sr)
    # Pure white noise has no clear voiced/silence split — SNR should be
    # at or below the low_snr threshold.
    assert snr < 6.0, f"expected SNR < 6 dB for pure noise, got {snr}"


def test_snr_negative_for_silence():
    audio, sr = _load("silence_5s.wav")
    snr = voice_audio.compute_snr_db(audio, sr)
    # No voiced content -> sentinel at the floor (-60 dB)
    assert snr <= 0.0


